import { useState } from 'react';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { 
  Search, 
  Filter, 
  Plus, 
  Edit, 
  Trash2, 
  Loader2,
  ChevronLeft,
  ChevronRight,
  RefreshCw,
  Eye,
  AlertTriangle,
  CheckCircle,
  XCircle,
} from 'lucide-react';
import { format } from 'date-fns';
import { db } from '../firebase/config.jsx';
import { 
  collection, 
  query, 
  where, 
  orderBy, 
  limit, 
  startAfter, 
  getDocs,
  getCountFromServer,
  updateDoc,
  doc,
  addDoc,
  deleteDoc,
  Timestamp
} from 'firebase/firestore';
import toast from 'react-hot-toast';

const ITEMS_PER_PAGE = 25;

export default function Tasks() {
  const [search, setSearch] = useState('');
  const [statusFilter, setStatusFilter] = useState('all');
  const [sortBy, setSortBy] = useState('createdAt_desc');
  const [currentPage, setCurrentPage] = useState(1);
  const [lastDoc, setLastDoc] = useState(null);
  const [showCreateModal, setShowCreateModal] = useState(false);
  const [editingTask, setEditingTask] = useState(null);
  const queryClient = useQueryClient();

  const buildQuery = (cursor = null) => {
    let q = collection(db, 'Tasks');
    const constraints = [orderBy(sortBy.split('_')[0], sortBy.split('_')[1]), limit(ITEMS_PER_PAGE)];
    
    if (cursor) {
      constraints.push(startAfter(cursor));
    }
    
    if (statusFilter === 'active') {
      constraints.unshift(where('isActive', '==', true));
    } else if (statusFilter === 'inactive') {
      constraints.unshift(where('isActive', '==', false));
    }
    
    return query(q, ...constraints);
  };

  const { data: tasksData, isLoading, refetch } = useQuery({
    queryKey: ['tasks', search, statusFilter, sortBy, currentPage],
    queryFn: async () => {
      if (search) {
        const q = query(collection(db, 'Tasks'), orderBy('createdAt', 'desc'), limit(500));
        const snap = await getDocs(q);
        return snap.docs
          .map(doc => ({ id: doc.id, ...doc.data() }))
          .filter(task => 
            task.title?.toLowerCase().includes(search.toLowerCase()) ||
            task.category?.toLowerCase().includes(search.toLowerCase())
          )
          .slice((currentPage - 1) * ITEMS_PER_PAGE, currentPage * ITEMS_PER_PAGE);
      }
      
      const q = buildQuery(currentPage > 1 ? lastDoc : null);
      const snap = await getDocs(q);
      const tasks = snap.docs.map(doc => ({ id: doc.id, ...doc.data() }));
      const newLastDoc = snap.docs[snap.docs.length - 1];
      setLastDoc(newLastDoc);
      return tasks;
    },
    placeholderData: (previousData) => previousData,
  });

  const { data: totalCount } = useQuery({
    queryKey: ['tasksCount', statusFilter, search],
    queryFn: async () => {
      if (search) return 0;
      let q = collection(db, 'Tasks');
      const constraints = [];
      if (statusFilter === 'active') {
        constraints.push(where('isActive', '==', true));
      } else if (statusFilter === 'inactive') {
        constraints.push(where('isActive', '==', false));
      }
      const snap = await getCountFromServer(query(q, ...constraints));
      return snap.data().count;
    },
  });

  const taskMutation = useMutation({
    mutationFn: async ({ task, isEdit }) => {
      const data = {
        ...task,
        updatedAt: Timestamp.now(),
      };
      delete data.id;
      
      if (isEdit) {
        await updateDoc(doc(db, 'Tasks', editingTask.id), data);
      } else {
        data.createdAt = Timestamp.now();
        await addDoc(collection(db, 'Tasks'), data);
      }
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['tasks'] });
      toast.success(editingTask ? 'Task updated' : 'Task created');
      setShowCreateModal(false);
      setEditingTask(null);
    },
    onError: () => toast.error(editingTask ? 'Failed to update task' : 'Failed to create task'),
  });

  const deleteMutation = useMutation({
    mutationFn: async (id) => {
      await deleteDoc(doc(db, 'Tasks', id));
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['tasks'] });
      toast.success('Task deleted');
    },
    onError: () => toast.error('Failed to delete task'),
  });

  const handleSubmit = (e) => {
    e.preventDefault();
    const formData = new FormData(e.currentTarget);
    const task = {
      title: formData.get('title'),
      description: formData.get('description'),
      category: formData.get('category'),
      points: parseInt(formData.get('points') || '0'),
      dailyLimit: parseInt(formData.get('dailyLimit') || '1'),
      isActive: formData.get('isActive') === 'on',
      isAutoGenerated: false,
    };
    taskMutation.mutate({ task, isEdit: !!editingTask });
  };

  const handleEdit = (task) => {
    setEditingTask(task);
    setShowCreateModal(true);
  };

  const handleDelete = async (id) => {
    if (!confirm('Delete this task?')) return;
    await deleteMutation.mutateAsync(id);
  };

  const tasks = tasksData || [];
  const totalPages = Math.ceil((totalCount || 0) / ITEMS_PER_PAGE);

  return (
    <div className="space-y-6 animate-fade-in">
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-dark-900">Tasks Management</h1>
          <p className="text-dark-500 mt-1">Create and manage tasks for users</p>
        </div>
        <div className="flex gap-2">
          <button className="btn-secondary" onClick={() => refetch()}>
            <RefreshCw className="w-4 h-4 mr-2" />
            Refresh
          </button>
          <button className="btn-primary" onClick={() => { setEditingTask(null); setShowCreateModal(true); }}>
            <Plus className="w-4 h-4 mr-2" />
            Add Task
          </button>
        </div>
      </div>

      <div className="card p-4">
        <div className="flex flex-col sm:flex-row gap-4">
          <div className="relative flex-1 max-w-md">
            <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-5 h-5 text-dark-400" />
            <input
              type="text"
              placeholder="Search by title, category..."
              value={search}
              onChange={(e) => { setSearch(e.target.value); setCurrentPage(1); }}
              className="input pl-10"
            />
          </div>
          <div className="flex gap-2">
            <select
              value={statusFilter}
              onChange={(e) => { setStatusFilter(e.target.value); setCurrentPage(1); }}
              className="input w-auto"
            >
              <option value="all">All</option>
              <option value="active">Active</option>
              <option value="inactive">Inactive</option>
            </select>
            <select
              value={sortBy}
              onChange={(e) => { setSortBy(e.target.value); setCurrentPage(1); }}
              className="input w-auto"
            >
              <option value="createdAt_desc">Newest First</option>
              <option value="createdAt_asc">Oldest First</option>
              <option value="points_desc">Highest Points</option>
              <option value="points_asc">Lowest Points</option>
              <option value="title_asc">Title A-Z</option>
            </select>
          </div>
        </div>
      </div>

      <div className="card overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full" role="table">
            <thead className="bg-dark-50 border-b border-dark-200">
              <tr>
                <th className="px-4 py-3 text-left text-sm font-semibold text-dark-600 uppercase tracking-wider">Task</th>
                <th className="px-4 py-3 text-left text-sm font-semibold text-dark-600 uppercase tracking-wider">Category</th>
                <th className="px-4 py-3 text-left text-sm font-semibold text-dark-600 uppercase tracking-wider">Points</th>
                <th className="px-4 py-3 text-left text-sm font-semibold text-dark-600 uppercase tracking-wider">Daily Limit</th>
                <th className="px-4 py-3 text-left text-sm font-semibold text-dark-600 uppercase tracking-wider">Status</th>
                <th className="px-4 py-3 text-left text-sm font-semibold text-dark-600 uppercase tracking-wider">Created</th>
                <th className="w-32 px-4 py-3 text-right text-sm font-semibold text-dark-600 uppercase tracking-wider">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-dark-100">
              {isLoading ? (
                <tr>
                  <td colSpan={7} className="px-4 py-12 text-center">
                    <div className="flex items-center justify-center gap-3">
                      <Loader2 className="w-6 h-6 animate-spin text-primary-600" />
                      <span className="text-dark-500">Loading tasks...</span>
                    </div>
                  </td>
                </tr>
              ) : tasks.length === 0 ? (
                <tr>
                  <td colSpan={7} className="px-4 py-12 text-center text-dark-500">
                    No tasks found
                  </td>
                </tr>
              ) : (
                tasks.map((task) => (
                  <tr key={task.id} className="hover:bg-dark-50 transition-colors">
                    <td className="px-4 py-3">
                      <p className="font-medium text-dark-900 truncate max-w-xs">{task.title}</p>
                      <p className="text-sm text-dark-500 truncate max-w-xs">{task.description}</p>
                    </td>
                    <td className="px-4 py-3">
                      <span className="badge badge-info">{task.category}</span>
                    </td>
                    <td className="px-4 py-3">
                      <div className="flex items-center gap-1">
                        <span className="font-mono text-dark-900">{task.points}</span>
                        <span className="text-xs text-dark-400">pts</span>
                      </div>
                    </td>
                    <td className="px-4 py-3">
                      <span className="font-mono text-dark-900">{task.dailyLimit}</span>
                    </td>
                    <td className="px-4 py-3">
                      <span className={'badge ' + (task.isActive ? 'badge-success' : 'badge-neutral')}>
                        {task.isActive ? 'Active' : 'Inactive'}
                      </span>
                    </td>
                    <td className="px-4 py-3 text-sm text-dark-500">
                      {task.createdAt?.toDate ? format(task.createdAt.toDate(), 'MMM dd, yyyy') : 'N/A'}
                    </td>
                    <td className="px-4 py-3 text-right">
                      <div className="flex items-center justify-end gap-1">
                        <button
                          onClick={() => handleEdit(task)}
                          className="p-2 rounded-lg text-dark-400 hover:text-primary-600 hover:bg-primary-50 transition-colors"
                          title="Edit"
                        >
                          <Edit className="w-5 h-5" />
                        </button>
                        <button
                          onClick={() => handleDelete(task.id)}
                          disabled={deleteMutation.isPending}
                          className="p-2 rounded-lg text-dark-400 hover:text-red-600 hover:bg-red-50 transition-colors"
                          title="Delete"
                        >
                          <Trash2 className="w-5 h-5" />
                        </button>
                      </div>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>

        {!isLoading && totalPages > 1 && (
          <div className="flex items-center justify-between px-4 py-4 border-t border-dark-200">
            <div className="text-sm text-dark-500">
              Page {currentPage} of {totalPages} ({totalCount || 0} total)
            </div>
            <div className="flex gap-2">
              <button
                onClick={() => setCurrentPage(p => Math.max(1, p - 1))}
                disabled={currentPage === 1}
                className="p-2 rounded-lg border border-dark-300 hover:bg-dark-100 disabled:opacity-50"
              >
                <ChevronLeft className="w-5 h-5" />
              </button>
              <button
                onClick={() => setCurrentPage(p => Math.min(totalPages, p + 1))}
                disabled={currentPage === totalPages}
                className="p-2 rounded-lg border border-dark-300 hover:bg-dark-100 disabled:opacity-50"
              >
                <ChevronRight className="w-5 h-5" />
              </button>
            </div>
          </div>
        )}
      </div>

      {/* Create/Edit Modal */}
      {(showCreateModal || editingTask) && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 p-4" onClick={() => { setShowCreateModal(false); setEditingTask(null); }}>
          <div className="bg-white rounded-xl shadow-xl max-w-md w-full max-h-[90vh] overflow-y-auto" onClick={e => e.stopPropagation()}>
            <div className="p-6 border-b border-dark-200 flex items-center justify-between">
              <h2 className="text-xl font-bold text-dark-900">{editingTask ? 'Edit Task' : 'Create Task'}</h2>
              <button onClick={() => { setShowCreateModal(false); setEditingTask(null); }} className="p-2 text-dark-400 hover:text-dark-600">×</button>
            </div>
            <form onSubmit={handleSubmit} className="p-6 space-y-4">
              <div>
                <label htmlFor="title" className="label">Title *</label>
                <input id="title" name="title" type="text" defaultValue={editingTask?.title || ''} required className="input" />
              </div>
              <div>
                <label htmlFor="description" className="label">Description</label>
                <textarea id="description" name="description" rows={3} defaultValue={editingTask?.description || ''} className="input" />
              </div>
              <div>
                <label htmlFor="category" className="label">Category *</label>
                <select id="category" name="category" defaultValue={editingTask?.category || 'General'} className="input" required>
                  <option value="General">General</option>
                  <option value="Survey">Survey</option>
                  <option value="Poll">Poll</option>
                  <option value="Quiz">Quiz</option>
                  <option value="Games">Games</option>
                  <option value="Engagement">Engagement</option>
                  <option value="Promotional">Promotional</option>
                </select>
              </div>
              <div className="grid grid-cols-2 gap-4">
                <div>
                  <label htmlFor="points" className="label">Points *</label>
                  <input id="points" name="points" type="number" min="1" defaultValue={editingTask?.points || 1} required className="input" />
                </div>
                <div>
                  <label htmlFor="dailyLimit" className="label">Daily Limit *</label>
                  <input id="dailyLimit" name="dailyLimit" type="number" min="1" defaultValue={editingTask?.dailyLimit || 1} required className="input" />
                </div>
              </div>
              <div className="flex items-center gap-2">
                <input id="isActive" name="isActive" type="checkbox" defaultChecked={editingTask?.isActive !== false} className="w-4 h-4 text-primary-600 rounded border-dark-300" />
                <label htmlFor="isActive" className="text-sm text-dark-700">Active</label>
              </div>
              <div className="flex gap-3 pt-4">
                <button type="button" onClick={() => { setShowCreateModal(false); setEditingTask(null); }} className="btn-outline flex-1">Cancel</button>
                <button type="submit" className="btn-primary flex-1" disabled={taskMutation.isPending}>
                  {taskMutation.isPending ? 'Saving...' : (editingTask ? 'Update' : 'Create')}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
}